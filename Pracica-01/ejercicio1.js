//(suma, resta, multiplicación, división y módulo) y muestre cada resultado por separado en
//consola.

//Paso 1: Declaracion de variables numericas para realizar las operaciones
let num1 = 10;
let num2 = 20;

//Paso 2: Calculo de las operaciones aritmeticas requeridas
let suma = num1 + num2;
let resta = num1 - num2;
let multiplicación = num1 * num2;
let modulo = num2 % num1;

//Paso 3: Impresion de los resultados en la consola con mensajes descriptivos
console.log(`La suma es : ${suma}`);
console.log(`La resta es: ${resta}`);
console.log(`La multiplicion es: ${multiplicación}`);
console.log(`El residuo de la operacion: ${modulo}`);